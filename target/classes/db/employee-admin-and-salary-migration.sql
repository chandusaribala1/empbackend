-- Employee management changes for the existing PostgreSQL database.
-- Run while connected to database: tm (or update your DB_URL accordingly).
-- This script preserves existing employee rows and IDs.
-- It does not drop tables, truncate data, or remove pagination.

BEGIN;

-- Registration creates the employee profile before salary/department are assigned.
-- Admin will populate salary and department later from the employee screen.
ALTER TABLE employee.employees
    ALTER COLUMN salary DROP NOT NULL;

-- Admin credentials are stored in PostgreSQL, never hard-coded in Java.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS employee.admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_admin_users_username UNIQUE (username)
);

-- Change these two values before running this script in your environment.
-- The password is stored as a BCrypt-compatible hash using pgcrypto's bf algorithm.
INSERT INTO employee.admin_users (username, password_hash, active)
VALUES ('admin', crypt('ChangeMe!2026', gen_salt('bf', 12)), TRUE)
ON CONFLICT (username) DO NOTHING;

-- Ensure existing employee login columns/index are available (safe if already present).
ALTER TABLE employee.employees
    ADD COLUMN IF NOT EXISTS username VARCHAR(50);

ALTER TABLE employee.employees
    ADD COLUMN IF NOT EXISTS password_hash VARCHAR(100);

CREATE UNIQUE INDEX IF NOT EXISTS uk_employee_username
    ON employee.employees (username);

CREATE UNIQUE INDEX IF NOT EXISTS uk_admin_users_username_lower
    ON employee.admin_users (lower(username));

COMMIT;

-- Verification 1: expected to show 106 if all 106 records are in this mapped table.
SELECT COUNT(*) AS employee_count
FROM employee.employees;

-- Verification 2: review first page and ensure all existing rows are present.
SELECT id, name, email, salary, department_id
FROM employee.employees
ORDER BY id
LIMIT 10;

-- Verification 3: confirm admin account exists (password is not exposed).
SELECT username, active, created_at
FROM employee.admin_users
ORDER BY id;

-- Diagnostic: if employee_count above is not 106, check whether the records
-- are stored in a different schema/table before changing application mappings.
SELECT table_schema, table_name
FROM information_schema.tables
WHERE table_name = 'employees'
  AND table_type = 'BASE TABLE'
ORDER BY table_schema;
